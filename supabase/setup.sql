-- ThriftMall bootstrap schema and access policies.
-- Intended for a NEW Supabase project. Do not rerun blindly against a live project.
-- For an existing deployment, use the versioned migrations in supabase/migrations/.

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  type text not null default 'buyer' check (type in ('buyer', 'seller')),
  name text not null default '',
  shop text,
  loc text,
  wa text,
  logo_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  seller_id uuid not null references public.profiles (id) on delete cascade,
  name text not null check (char_length(name) <= 120),
  price numeric(10, 2) not null check (price >= 0),
  size text not null,
  cond text not null,
  cat text not null check (cat in ('Accessories', 'Clothing', 'Rare Finds')),
  img_url text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.profile_preferences (
  user_id uuid primary key references auth.users (id) on delete cascade,
  follows text[] not null default '{}',
  updates_opt_in boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.profile_preferences enable row level security;

-- Replace inherited/default privileges with the minimum required by the browser app.
revoke all privileges on table public.profiles from public, anon, authenticated;
grant select (id, type, name, shop, loc, wa, logo_url) on table public.profiles to anon, authenticated;
grant update (name, shop, loc, wa, logo_url) on table public.profiles to authenticated;

revoke all privileges on table public.products from public, anon, authenticated;
grant select on table public.products to anon, authenticated;
grant insert (seller_id, name, price, size, cond, cat, img_url) on table public.products to authenticated;
grant delete on table public.products to authenticated;

do $$
declare seq_name text;
begin
  seq_name := pg_get_serial_sequence('public.products', 'id');
  if seq_name is not null then
    execute format('grant usage, select on sequence %s to authenticated', seq_name);
  end if;
end;
$$;

revoke all privileges on table public.profile_preferences from public, anon, authenticated;
grant select, insert, update on table public.profile_preferences to authenticated;

drop policy if exists "Read seller profiles and own profile" on public.profiles;
create policy "Read seller profiles and own profile"
  on public.profiles for select
  using (type = 'seller' or id = (select auth.uid()));

drop policy if exists "Update own profile" on public.profiles;
create policy "Update own profile"
  on public.profiles for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

drop policy if exists "Public can read products" on public.products;
create policy "Public can read products"
  on public.products for select
  using (true);

drop policy if exists "Sellers can add their own products" on public.products;
create policy "Sellers can add their own products"
  on public.products for insert to authenticated
  with check (
    seller_id = (select auth.uid())
    and exists (
      select 1 from public.profiles
      where id = (select auth.uid()) and type = 'seller'
    )
  );

drop policy if exists "Sellers can delete their own products" on public.products;
create policy "Sellers can delete their own products"
  on public.products for delete to authenticated
  using (seller_id = (select auth.uid()));

drop policy if exists "Users can read their own preferences" on public.profile_preferences;
create policy "Users can read their own preferences"
  on public.profile_preferences for select to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "Users can create their own preferences" on public.profile_preferences;
create policy "Users can create their own preferences"
  on public.profile_preferences for insert to authenticated
  with check (user_id = (select auth.uid()));

drop policy if exists "Users can update their own preferences" on public.profile_preferences;
create policy "Users can update their own preferences"
  on public.profile_preferences for update to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

create or replace function public.create_thriftmall_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  metadata jsonb := new.raw_user_meta_data;
  account_type text := metadata ->> 'type';
begin
  if account_type is null or account_type not in ('buyer', 'seller') then
    account_type := 'buyer';
  end if;

  insert into public.profiles (id, type, name, shop, loc, wa)
  values (
    new.id,
    account_type,
    coalesce(nullif(metadata ->> 'name', ''), 'Thriftmall member'),
    nullif(metadata ->> 'shop', ''),
    nullif(metadata ->> 'loc', ''),
    nullif(metadata ->> 'wa', '')
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

revoke all on function public.create_thriftmall_profile() from public, anon, authenticated;

drop trigger if exists on_auth_user_created_thriftmall on auth.users;
create trigger on_auth_user_created_thriftmall
  after insert on auth.users
  for each row execute function public.create_thriftmall_profile();

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('images', 'images', true, 5242880, array['image/jpeg'])
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Public can view Thriftmall images" on storage.objects;
create policy "Public can view Thriftmall images"
  on storage.objects for select
  using (bucket_id = 'images');

drop policy if exists "Users can upload to their own Thriftmall folder" on storage.objects;
create policy "Users can upload to their own Thriftmall folder"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'images'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );
